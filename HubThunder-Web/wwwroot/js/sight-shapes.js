(() => {
  'use strict';
  const path = (xy, closed = true, filled = false) => ({ points: xy.map(([x, y]) => ({ x, y })), closed, filled });
  const polygon = (n, radius = 1, phase = Math.PI / 2) => Array.from({ length: n }, (_, i) => [radius * Math.cos(phase + i * Math.PI * 2 / n), radius * Math.sin(phase + i * Math.PI * 2 / n)]);
  const circle = (r = 1, filled = false) => path(polygon(64, r), true, filled);
  const star = (n, inner) => path(Array.from({ length: n * 2 }, (_, i) => { const t = Math.PI / 2 + i * Math.PI / n, r = i % 2 ? inner : 1; return [Math.cos(t) * r, Math.sin(t) * r]; }));
  const rays = (n, inner = .35, phase = 0) => Array.from({ length: n }, (_, i) => { const t = phase + i * Math.PI * 2 / n; return path([[Math.cos(t) * inner, Math.sin(t) * inner], [Math.cos(t), Math.sin(t)]], false); });
  const plus = [[-.22,1],[.22,1],[.22,.22],[1,.22],[1,-.22],[.22,-.22],[.22,-1],[-.22,-1],[-.22,-.22],[-1,-.22],[-1,.22],[-.22,.22]];
  const rotate = (xy, angle) => xy.map(([x,y]) => [x*Math.cos(angle)-y*Math.sin(angle),x*Math.sin(angle)+y*Math.cos(angle)]);
  const box = path([[-1,1],[1,1],[1,-1],[-1,-1]]);
  const definitions = [];
  const add = (id, name, category, paths) => definitions.push({ id, name, category, paths });
  add('square', 'Square', 'Basic', [box]);
  add('triangle', 'Triangle', 'Basic', [path([[0,1],[1,-1],[-1,-1]])]);
  add('circle', 'Circle', 'Basic', [circle()]);
  add('diamond', 'Diamond', 'Basic', [path(polygon(4))]);
  for (const [id,n] of [['pentagon',5],['hexagon',6],['octagon',8]]) add(id, id[0].toUpperCase()+id.slice(1), 'Basic', [path(polygon(n))]);
  add('star', 'Star', 'Basic', [star(5,.42)]);
  add('animeStar', 'Anime Star', 'Basic', [star(4,.16)]);
  add('heart', 'Heart', 'Symbols', [path(Array.from({length:64},(_,i)=>{const t=i*Math.PI/32;return [16*Math.sin(t)**3/17,(13*Math.cos(t)-5*Math.cos(2*t)-2*Math.cos(3*t)-Math.cos(4*t))/17];}))]);
  add('checkmark', 'Checkmark', 'Symbols', [path([[-1,0],[-.75,.2],[-.25,-.35],[.85,1],[1,.8],[-.25,-.8]])]);
  add('cross', 'Cross', 'Symbols', [path(rotate(plus,Math.PI/4))]);
  add('plus', 'Plus', 'Symbols', [path(plus)]);
  add('minus', 'Minus', 'Symbols', [path([[-1,.18],[1,.18],[1,-.18],[-1,-.18]])]);
  add('bracket', 'Bracket', 'Symbols', [path([[.4,1],[-.4,1],[-.4,-1],[.4,-1]],false)]);
  add('arrow', 'Arrow', 'Markers', [path([[-1,.2],[.2,.2],[.2,.7],[1,0],[.2,-.7],[.2,-.2],[-1,-.2]])]);
  add('chevron', 'Chevron', 'Markers', [path([[-1,-.6],[0,1],[1,-.6],[.65,-.8],[0,.3],[-.65,-.8]])]);
  add('direction', 'Direction', 'Markers', [path([[0,-1],[0,1],[-.5,.4],[0,1],[.5,.4]],false)]);
  add('distance', 'Distance marks', 'Markers', [path([[-1,0],[1,0]],false), ...[-1,-.5,0,.5,1].map(x=>path([[x,0],[x,x===0?.6:.3]],false))]);
  add('impactMarker', 'Impact marker', 'Markers', [circle(.3), ...rays(4,.55,Math.PI/4)]);
  add('target', 'Target', 'Crosshair', [circle(),circle(.65),circle(.3)]);
  add('dot', 'Dot', 'Crosshair', [circle(1,true)]);
  add('ring', 'Ring', 'Crosshair', [circle(1,true),circle(.7,true)]);
  add('crosshair', 'Crosshair', 'Crosshair', rays(4,.2));
  add('crosshairRing', 'Ring crosshair', 'Crosshair', [circle(.55),...rays(4,.7)]);
  add('openTarget', 'Open target', 'Crosshair', [path([[-1,.5],[-1,1],[-.5,1]],false),path([[.5,1],[1,1],[1,.5]],false),path([[1,-.5],[1,-1],[.5,-1]],false),path([[-.5,-1],[-1,-1],[-1,-.5]],false)]);
  add('tank', 'Armour symbol', 'Military', [path([[-1,.65],[1,.65],[1,-.65],[-1,-.65]]), path(polygon(32).map(([x,y])=>[x*.65,y*.35]))]);
  add('infantry', 'Infantry symbol', 'Military', [path([[-1,.65],[1,.65],[1,-.65],[-1,-.65]]),path([[-1,.65],[1,-.65]],false),path([[-1,-.65],[1,.65]],false)]);
  add('aircraft', 'Aircraft symbol', 'Military', [path([[0,1],[.15,.15],[1,-.2],[1,-.4],[.15,-.25],[.1,-.75],[.4,-.9],[.4,-1],[0,-.9],[-.4,-1],[-.4,-.9],[-.1,-.75],[-.15,-.25],[-1,-.4],[-1,-.2],[-.15,.15]])]);
  add('airDefense', 'Air defence', 'Military', [path([[-1,-.6],[-.7,0],[0,.6],[.7,0],[1,-.6]],false),path([[0,-1],[0,.6]],false)]);
  add('waypoint', 'Waypoint', 'Military', [path([[0,1],[.7,.2],[.4,-.2],[0,-1],[-.4,-.2],[-.7,.2]]),circle(.2)]);
  // Country marks are monochrome outlines; BLK has no per-shape RGB palette.
  add('roundel', 'Roundel outline', 'Country', [circle(),circle(.66),circle(.33)]);
  add('starRoundel', 'Star roundel', 'Country', [circle(),star(5,.4)]);
  add('starBars', 'Star and bars', 'Country', [star(5,.4),path([[-1,-.3],[-1.5,-.3],[-1.5,.3],[-1,.3]],false),path([[1,-.3],[1.5,-.3],[1.5,.3],[1,.3]],false)]);
  add('flag', 'Flag outline', 'Country', [path([[-.8,-1],[-.8,1],[1,1],[1,0],[-.8,0]],false)]);
  add('tricolor', 'Tricolour outline', 'Country', [box,path([[-.33,-1],[-.33,1]],false),path([[.33,-1],[.33,1]],false)]);
  add('explosion', 'Explosion', 'Effects', [star(11,.46)]);
  add('impact', 'Impact', 'Effects', [star(7,.3),circle(.15)]);
  add('spark', 'Spark', 'Effects', rays(6,.12));
  add('flash', 'Flash', 'Effects', [path([[.1,1],[-.8,-.1],[-.15,-.1],[-.4,-1],[.8,.2],[.1,.2]])]);
  add('smoke', 'Smoke contour', 'Effects', [path(Array.from({length:80},(_,i)=>{const t=i*Math.PI/40,r=.75+.15*Math.cos(7*t);return [r*Math.cos(t),r*Math.sin(t)];}))]);
  add('burst', 'Burst', 'Effects', rays(12,.55));
  add('starburst', 'Starburst', 'Effects', [star(16,.55)]);
  add('hitMarker', 'Hit marker', 'Effects', rays(4,.4,Math.PI/4));
  add('damageMarker', 'Damage marker', 'Effects', [path([[-1,.7],[0,1],[1,.7],[.7,.45],[0,.7],[-.7,.45]])]);
  add('shockwave', 'Shockwave', 'Effects', [circle(),circle(.85),circle(.5)]);
  add('radialBurst', 'Radial burst', 'Effects', rays(24,.7));
  const attention = [path([[0,.5],[0,-.25]],false),path([[-.06,-.55],[.06,-.55],[.06,-.7],[-.06,-.7]],true,true)];
  add('warning', 'Warning', 'Effects', [path([[0,1],[1,-1],[-1,-1]]),...attention]);
  add('attention', 'Attention', 'Effects', [circle(),...attention]);
  add('arrowBurst', 'Arrow burst', 'Effects', Array.from({length:8},(_,i)=>path(rotate([[.4,0],[1,0],[.7,.2],[1,0],[.7,-.2]],i*Math.PI/4),false)));
  add('free', 'Free shape', 'Basic', [path([[-1,-.6],[-.7,.7],[-.15,-.5],[.35,.9],[1,-.2]],false)]);
  const create = (id, a, b) => {
    const definition = definitions.find(d => d.id === id) || definitions[0];
    const cx=(a.x+b.x)/2, cy=(a.y+b.y)/2, rx=Math.abs(b.x-a.x)/2, ry=Math.abs(b.y-a.y)/2;
    if (id === 'circle') return {type:'circle',center:{x:cx,y:cy},radius:Math.max(.001,Math.min(rx,ry))};
    return {type:'shape',kind:id,points:[],paths:definition.paths.map(p=>({...p,points:p.points.map(v=>({x:cx+v.x*rx,y:cy+v.y*ry}))}))};
  };
  const api = { definitions, create };
  if (typeof module !== 'undefined') module.exports = api;
  if (typeof window !== 'undefined') window.hubSightShapes = api;
})();
